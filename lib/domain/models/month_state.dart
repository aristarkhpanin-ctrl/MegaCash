/// Состояние месячного цикла.
///
/// Главный экран рисуется по текущему состоянию, а не по набору разрозненных
/// флагов. Смена месяца определяется сравнением ключа последнего набора
/// предложений с текущим: при расхождении — переход в [needsScreenshots]
/// и плашка на главном экране.
enum MonthState {
  /// Карт нет вообще.
  noCards,

  /// Новый месяц, категории не загружены.
  needsScreenshots,

  /// Идёт распознавание.
  recognizing,

  /// Проверка распознанного.
  reviewing,

  /// Рекомендация показана, можно перебрасывать.
  recommended,

  /// Ждём, пока пользователь активирует категории в банках.
  awaitingActivation,

  /// Всё готово, обычная работа.
  active,
}
