import 'package:flutter/widgets.dart';

/// Рекламный модуль.
///
/// За интерфейсом, потому что сеть точно будет меняться: AdMob из России
/// ушёл, работающие варианты — Яндекс и myTarget, и выбирать между ними
/// придётся по деньгам, а не по коду.
///
/// Правило, которое интерфейс обязан соблюдать: рекламы нет на экране
/// ответа. Человек открывает его у кассы, на две секунды, чтобы узнать
/// одну вещь. Баннер там — прямой способ, чтобы приложением перестали
/// пользоваться.
abstract interface class AdsProvider {
  /// Готовит модуль: инициализация сети, загрузка первого баннера.
  Future<void> prepare();

  /// Виджет баннера или null, если показывать нечего.
  ///
  /// Null — обычное дело: реклама не пришла, сети нет, показы кончились.
  /// Место под баннер в таком случае схлопывается, а не зияет пустотой.
  Widget? banner(BuildContext context);

  Future<void> dispose();
}

/// Заглушка: рекламы нет.
///
/// Работает, пока не подключена настоящая сеть. Приложение с ней
/// полностью функционально — это и есть проверка того, что реклама
/// действительно за интерфейсом, а не вплетена в экраны.
class NoAdsProvider implements AdsProvider {
  const NoAdsProvider();

  @override
  Future<void> prepare() async {}

  @override
  Widget? banner(BuildContext context) => null;

  @override
  Future<void> dispose() async {}
}
